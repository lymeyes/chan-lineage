count = 0
for node_id, (name, school, bio, sayings) in DATA.items():
    if node_id not in byid:
        print("WARN node not found:", node_id)
        continue
    teacher = teacher_of(node_id)
    rec = {
        "id": node_id,
        "name": name,
        "school": school,
        "teacher": teacher,
        "bio": bio,
        "sayings": sayings,
        "status": "draft",
        "verify": "据《五灯会元》整理，待 CBETA 逐字校核原文与卷次；师承以谱系父节点为准。",
    }
    with open(os.path.join(OUT, node_id + ".yaml"), "w", encoding="utf-8") as f:
        yaml.safe_dump(rec, f, allow_unicode=True, sort_keys=False, default_flow_style=False, width=1000)
    count += 1

print(f"已升格 {count} 份跨宗派 draft 卡。")
