DEFAULT_SRC = "景德传灯录 / 五灯会元（卷次待核）"
DEFAULT_CBETA = "T51n2076（景德传灯录）；X（五灯会元·卍续藏，编号待核）"


def main():
    changed = 0
    for fp in sorted(glob.glob(os.path.join(PATRIARCHS, "*.yaml"))):
        with open(fp, encoding="utf-8") as f:
            d = yaml.safe_load(f)
        if not d or d.get("status") != "draft":
            continue

        # 1) 补锚点（不覆盖已有）
        base = os.path.basename(fp)[:-5]
        if "source_ref" not in d or not d.get("source_ref"):
            d["source_ref"] = CITATIONS.get(base, (DEFAULT_SRC, DEFAULT_CBETA))[0]
        if "cbeta" not in d or not d.get("cbeta"):
            d["cbeta"] = CITATIONS.get(base, (DEFAULT_SRC, DEFAULT_CBETA))[1]

        # 2) 透明字段：证据等级 + 核验状态（统一覆写，确保全量一致）
        d["evidence"] = "primary"
        d["verify_status"] = "anchor_only"

        with open(fp, "w", encoding="utf-8") as f:
            yaml.safe_dump(d, f, allow_unicode=True, sort_keys=False, default_flow_style=False)
        changed += 1
    print(f"已规范化 draft 卡: {changed} 份（补锚点 + evidence/verify_status 字段）")


if __name__ == "__main__":
    main()
